class Flower:
    def __init__(self, name, color, height):
        self.name = name
        self.color = color
        self.height = height

f1 = Flower("Rose","Red","10 cm")
f2 = Flower("Sunflower","Yellow","5 cm")

print(f1.name)
print(f2.name)

print(f1.color)
print(f1.color)

print(f1.height)
print(f1.height)
